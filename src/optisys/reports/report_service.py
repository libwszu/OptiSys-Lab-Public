class ReportService:
    """UI-facing facade.  Keeps no state and never mutates a run."""

    def __init__(self, runs_dir: Path, *, verdict_root: Path | None = None) -> None:
        self.runs_dir = Path(runs_dir)
        self.verdict_root = verdict_root or Path.cwd()

    def verdict(self) -> dict[str, Any]:
        return load_verdict(self.verdict_root)

    def strip(self) -> dict[str, Any]:
        return science_strip(self.verdict())

    def build(self, run_dir: Path, *, title: str | None = None,
              formats: tuple[str, ...] = ("html", "markdown"),
              out_dir: Path | None = None) -> ReportResult:
        run_dir = Path(run_dir)
        status_path = run_dir / "run_status.json"
        if status_path.is_file():
            try:
                status = json.loads(status_path.read_text(encoding="utf-8"))
            except json.JSONDecodeError:
                status = {}
            if status.get("gate") == "G4":
                if out_dir is None:
                    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
                    out_dir = self.runs_dir / "_derived" / run_dir.name / f"{stamp}_report"
                from optisys.reports.report_g4 import render_g4_report

                return render_g4_report(
                    run_dir, out_dir, title=title or f"OptiSys-Lab G4 工程报告 · {run_dir.name}",
                    verdict_root=self.verdict_root, formats=formats,
                )
        summary = load_run(run_dir)
        if out_dir is None:
            stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
            out_dir = self.runs_dir / "_derived" / summary.run_id / f"{stamp}_report"
        spec = ReportSpec(
            run_dir=run_dir,
            out_dir=out_dir,
            title=title or f"OptiSys-Lab {summary.gate} 工程报告",
            formats=formats,
        )
        return render_report(spec, verdict=self.verdict(), summary=summary)

    def build_all_latest(self, *, formats: tuple[str, ...] = ("html", "markdown")
                         ) -> list[ReportResult]:
        from optisys.presentation.run_repository import load_latest_per_gate

        latest = load_latest_per_gate(self.runs_dir)
        results = []
        for gate in ("G0", "G1", "G2"):
            summary = latest.get(gate)
            if summary is None:
                continue
            results.append(self.build(summary.path, formats=formats))
        return results
