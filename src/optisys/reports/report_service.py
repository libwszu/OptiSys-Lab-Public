"""ReportService - offline-capable reports for G0 / G1 / G2 / G3-demo / G4.

Independent of the UI.  A report is a pure function of a run directory plus the
inheritance verdict, so it can be regenerated in CI without Streamlit.

Design rules that this module enforces
--------------------------------------
1. **Never writes into a run directory.**  Output goes to
   ``runs/_derived/<run_id>/<stamp>_<kind>/`` unless an explicit ``out_dir`` is
   given.
2. **The science banner is not optional.**  Every report carries the G2
   inheritance status strip (``G2_PREREG_FEASIBILITY_NOT_ESTABLISHED`` etc.).
   A report that cannot read the verdict file renders the strip as ``UNKNOWN``
   and says so, rather than omitting it.
3. **Figures are evidence, not decoration.**  Every embedded image is listed
   with its SHA-256 next to the numbers, and the report states that numbers are
   rebuilt from CSV/JSON, not read off the image.
4. **Missing means missing.**  No ``0`` substitution, no placeholder numbers.
   Optional PDF export reports ``NOT_DELIVERED`` with the reason when no
   renderer is installed.
"""

