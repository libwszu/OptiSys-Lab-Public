def _section_metrics(summary: RunSummary) -> str:
    if not summary.candidates:
        return ("<h2>4. 精度指标</h2>"
                f"<p class='muted'>该 run 无候选级指标（{summary.gate}）；"
                "逐项计数见上一节。</p>")
    rows = []
    for name in CANDIDATE_ORDER:
        m = summary.candidates.get(name)
        if m is None:
            rows.append([name, "NOT_AVAILABLE", "", "", "", "", ""])
            continue
        rows.append([
            name,
            _num(m.n_attempted, 0),
            _num(m.n_valid, 0),
            _pct(m.failure_rate),
            _num(m.rmse_mm),
            _num(m.p95_abs_mm),
            _num(m.bias_mm),
        ])
    out = ["<h2>4. 精度、P95、偏差与失败率</h2>",
           _table(["候选", "尝试帧", "有效帧", "失败率", "RMSE (mm)",
                   "P95|e| (mm)", "bias (mm)"], rows, "全尝试帧口径")]

    est_rows = []
    for name in CANDIDATE_ORDER:
        m = summary.candidates.get(name)
        if m is None:
            continue
        for estimator in ESTIMATOR_ORDER:
            sub = m.by_estimator.get(estimator)
            if sub is None:
                continue
            est_rows.append([name, estimator, _num(sub.n_valid, 0),
                             _pct(sub.failure_rate), _num(sub.rmse_mm),
                             _num(sub.p95_abs_mm)])
    if est_rows:
        out.append(_table(["候选", "估计器", "有效帧", "失败率", "RMSE (mm)",
                           "P95|e| (mm)"], est_rows, "按估计器拆分"))
        out.append(
            "<p class='muted'>三估计器：<code>centroid</code>（加权质心）、"
            "<code>gaussian_2d</code>（点采样二维高斯拟合，σ 下界 1.0 px 导致 "
            "MODEL_MISMATCH，有效率因此显著偏低）、"
            "<code>gaussian_2d_integrated</code>（面积积分高斯拟合）。"
            "其中 <code>gaussian_2d</code> 的低有效率是<b>模型不匹配</b>，"
            "不是传感器失效，不能读作系统失败率。</p>")

    out.append(
        "<h3>配对口径 vs 全尝试口径</h3>"
        "<p>上表为<b>全尝试帧</b>口径（分母 = n_attempted）。"
        "配对比较只在<b>两候选都有效</b>的共同帧上计算 RMSE，两者分母不同，"
        "数值不可混用。配对 ΔRMSE 见第 5 节。</p>")

    if summary.candidates.get("baseline") is not None:
        out.append(
            "<h3>robust 的权衡（G2-07）</h3>"
            "<p>robust 的 RMSE 低于 baseline，但失败率高于 baseline。"
            "本报告<b>不做</b>单一排名，也不输出「最优设计」。三指标必须同屏阅读。</p>")
    return "".join(out)


def _section_paired(summary: RunSummary) -> str:
    if summary.gate != "G2" or not summary.candidates:
        return ""
    path = summary.path / "independent_validation" / "ci_results.json"
    if not path.is_file():
        return ("<h2>5. 配对比较与置信区间</h2>"
                "<p class='muted'>NOT_AVAILABLE — ci_results.json 缺失。</p>")
    try:
        ci = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return ("<h2>5. 配对比较与置信区间</h2>"
                "<p class='muted'>NOT_AVAILABLE — ci_results.json 不可解析。</p>")

    rows = []
    for pair, payload in sorted(ci.items()):
        if not isinstance(payload, dict):
            continue
        for metric in ("rmse", "failure_rate"):
            block = payload.get(metric)
            if not isinstance(block, dict):
                continue
            rows.append([
                pair,
                metric,
                _num(block.get("delta")),
                f"[{_num(block.get('ci_low'))}, {_num(block.get('ci_high'))}]",
                "yes" if block.get("excludes_zero") else "no",
                _num(block.get("n_assemblies"), 0),
                _num(block.get("n_boot"), 0),
            ])
    if not rows:
        return ("<h2>5. 配对比较与置信区间</h2>"
                "<p class='muted'>NOT_AVAILABLE — ci_results.json 无可识别条目。</p>")
    return (
        "<h2>5. 配对比较与置信区间</h2>"
        + _table(["配对", "指标", "Δ", "95% CI", "排除 0", "装配数", "bootstrap 次数"],
                 rows, "按 assembly_id 聚类的配对 bootstrap")
        + "<p class='muted'>Δ = 后一候选 − 前一候选。RMSE 越低越好。"
        "CI 排除 0 仅说明差异方向稳定，<b>不</b>说明该设计在工程上可用。</p>"
        f"<p class='muted'>ci_results.json SHA-256: "
        f"<span class='mono hash'>{_e(sha256_file(path))}</span></p>"
    )


