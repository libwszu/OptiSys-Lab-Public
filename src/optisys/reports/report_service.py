def _summary_figure_list(run_dir: Path) -> dict[str, str]:
    figures: dict[str, str] = {}
    fig_dir = run_dir / "figures"
    if fig_dir.is_dir():
        for path in sorted(fig_dir.glob("*.png")):
            figures[f"figures/{path.name}"] = sha256_file(path)
    return figures


