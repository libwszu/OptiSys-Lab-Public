def load_verdict(root: Path | None = None) -> dict[str, Any]:
    """Read the machine-readable inheritance verdict.

    Returns a dict with ``available: False`` and a ``reason`` when the file is
    missing or unparsable.  Callers must render the banner as ``UNKNOWN`` in
    that case; they must not silently drop the banner.
    """

    root = root or Path.cwd()
    path = root / VERDICT_PATH
    if not path.is_file():
        return {"available": False, "reason": f"{VERDICT_PATH} not found"}
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        return {"available": False, "reason": f"unparsable verdict: {exc}"}
    if not isinstance(payload, dict):
        return {"available": False, "reason": "verdict is not an object"}
    payload["available"] = True
    payload["_sha256"] = sha256_file(path)
    return payload


def science_strip(verdict: dict[str, Any]) -> dict[str, Any]:
    """The status strip carried by the UI and every report."""

    if not verdict.get("available"):
        return {
            "state": "UNKNOWN",
            "reason": verdict.get("reason", "verdict unavailable"),
            "tokens": [],
            "historical_execution": "UNKNOWN",
            "prereg_compliance": "UNKNOWN",
            "numerical_verification": "UNKNOWN",
            "claim_allowed": "UNKNOWN",
        }
    return {
        "state": "KNOWN",
        "reason": "",
        "tokens": list(SCIENCE_TOKENS),
        "historical_execution": verdict.get("historical_g2_execution"),
        "prereg_compliance": verdict.get("original_prereg_compliance"),
        "numerical_verification": verdict.get("as_run_numerical_verification"),
        "stratified_repair": verdict.get("stratified_panel_repair"),
        "claim_allowed": verdict.get("scientific_claim_allowed"),
        "verdict_sha256": verdict.get("_sha256"),
    }


# ---------------------------------------------------------------------------
# formatting helpers
# ---------------------------------------------------------------------------
def _e(value: Any) -> str:
    return html.escape("" if value is None else str(value))


def _num(value: Any, digits: int = 4) -> str:
    if value is None:
        return "NOT_AVAILABLE"
    if isinstance(value, float):
        if value != value:
            return "NOT_AVAILABLE"
        return f"{value:.{digits}f}"
    return str(value)


def _pct(value: Any) -> str:
    if value is None or (isinstance(value, float) and value != value):
        return "NOT_AVAILABLE"
    return f"{float(value) * 100:.2f}%"


def _table(headers: Sequence[str], rows: Sequence[Sequence[Any]],
           caption: str = "") -> str:
    if not rows:
        return f"<p class='muted'>{_e(caption or 'NO_ROWS')}</p>"
    head = "".join(f"<th>{_e(h)}</th>" for h in headers)
    body = "".join(
        "<tr>" + "".join(f"<td>{_e(c)}</td>" for c in row) + "</tr>" for row in rows
    )
    cap = f"<caption>{_e(caption)}</caption>" if caption else ""
    return (f"<table>{cap}<thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>")


