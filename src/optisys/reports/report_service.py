def render_report(spec: ReportSpec, *, verdict: dict[str, Any] | None = None,
                  summary: RunSummary | None = None) -> ReportResult:
    """Render HTML (+Markdown) for one run.  Never touches the run directory."""

    run_dir = Path(spec.run_dir)
    out_dir = Path(spec.out_dir)
    verdict = verdict if verdict is not None else load_verdict()
    summary = summary if summary is not None else load_run(run_dir)

    out_dir.mkdir(parents=True, exist_ok=True)
    frozen_untouched = out_dir.resolve() != run_dir.resolve()

    fig_html, figures = _section_figures(summary, include=spec.include_figures)

    source_manifest = dict(summary.files)
    body = "".join([
        f"<h1>{_e(spec.title)}</h1>",
        f"<p class='muted'>{_e(summary.run_id)} · {_e(summary.gate)} · "
        f"schema {_e(summary.schema_version)}</p>",
        _banner(verdict),
        _section_header(summary, verdict),
        _section_assumptions(summary),
        _section_dataset(summary),
        _section_metrics(summary),
        _section_paired(summary),
        _section_strategy_ab(summary),
        fig_html,
        _section_inherited(verdict),
        _section_limits(summary, verdict),
        _section_repro(summary, source_manifest),
    ])
    stamp = datetime.now(timezone.utc).isoformat(timespec="seconds")
    html_text = (
        "<!DOCTYPE html><html lang='zh-CN'><head><meta charset='utf-8'>"
        "<meta name='viewport' content='width=device-width,initial-scale=1'>"
        f"<title>{_e(spec.title)} · {_e(summary.run_id)}</title>"
        f"<style>{_CSS}</style></head><body><main>{body}"
        f"<footer>生成时间 {_e(stamp)} · OptiSys-Lab · "
        f"证据等级 <b>{_e(summary.evidence.evidence_level)}</b> · "
        f"{_e(summary.evidence.note)}</footer></main></body></html>"
    )

    md_text = _render_markdown(spec, summary, verdict, figures)

    present = [t for t in SCIENCE_TOKENS if t in html_text]

    result = ReportResult(
        run_id=summary.run_id,
        html_path=None,
        markdown_path=None,
        pdf_status="NOT_DELIVERED",
        pdf_reason="no PDF renderer installed (reportlab / weasyprint / fpdf all absent)",
        bytes_html=0,
        bytes_markdown=0,
        science_tokens_present=present,
        figures_indexed=figures,
        frozen_run_untouched=frozen_untouched,
        generated_at_utc=stamp,
    )

    if "html" in spec.formats:
        path = out_dir / "report.html"
        path.write_text(html_text, encoding="utf-8")
        result.html_path = path
        result.bytes_html = len(html_text.encode("utf-8"))
        if (run_dir / "figures").is_dir():
            shutil.copytree(run_dir / "figures", out_dir / "figures", dirs_exist_ok=True)
    if "markdown" in spec.formats:
        path = out_dir / "report.md"
        path.write_text(md_text, encoding="utf-8")
        result.markdown_path = path
        result.bytes_markdown = len(md_text.encode("utf-8"))
    if "pdf" in spec.formats:
        result.pdf_status = "NOT_DELIVERED"
        result.pdf_reason = ("pdf requested but no renderer is installed; "
                             "install reportlab or weasyprint and re-run")
    return result


def _render_markdown(spec: ReportSpec, summary: RunSummary, verdict: dict[str, Any],
                     figures: dict[str, str]) -> str:
    lines: list[str] = [
        f"# {spec.title}",
        "",
        f"- run: `{summary.run_id}`",
        f"- gate: `{summary.gate}` · schema `{summary.schema_version}`",
        f"- model level: `{summary.model_level}`",
        f"- evidence level: `{summary.evidence.evidence_level}`",
        f"- status: `{summary.status}` · scientific: `{summary.scientific_status}`",
        f"- config sha256: `{summary.config_sha256}`",
        "",
    ]
    strip = science_strip(verdict)
    if strip["state"] == "UNKNOWN":
        lines += [f"> **科学状态 UNKNOWN** — {strip['reason']}", ""]
    else:
        lines += [
            "> **科学状态 QUALIFIED_ONLY — 不是未受限的 PASS**",
            ">",
            f"> 历史执行为 `PASS_RECORDED`；预注册合规性 "
            f"`{strip['prereg_compliance']}`；数值核验 "
            f"`{strip['numerical_verification']}`。",
            ">", "> 必须同屏携带：" ,
        ] + [f"> - `{t}`" for t in strip["tokens"]] + [""]

    if summary.candidates:
        lines += ["## 精度指标（全尝试帧口径）", "",
                  "| 候选 | 尝试 | 有效 | 失败率 | RMSE (mm) | P95 (mm) | bias (mm) |",
                  "|---|---|---|---|---|---|---|"]
        for name in CANDIDATE_ORDER:
            m = summary.candidates.get(name)
            if m is None:
                lines.append(f"| {name} | NOT_AVAILABLE | | | | | |")
                continue
            lines.append(
                f"| {name} | {m.n_attempted} | {m.n_valid} | {_pct(m.failure_rate)} | "
                f"{_num(m.rmse_mm)} | {_num(m.p95_abs_mm)} | {_num(m.bias_mm)} |")
        lines.append("")

    if figures:
        lines += ["## 图件", ""]
        for rel, digest in figures.items():
            lines.append(f"- `{rel}` — SHA-256 `{digest}`")
        lines.append("")

    missing = summary.missing_reasons
    if missing:
        lines += ["## 缺失项", ""] + [f"- {m}" for m in missing] + [""]

    lines += [
        "## 边界",
        "",
        "- 无实测数据；证据层级上限 `SIMULATED` / `CROSS_CHECKED`。",
        "- G4（976 nm）是独立模拟案例；本 G2 run 不包含 G4 结果。",
        "- 主面板仅 medium 条件，不得跨条件外推。",
        "- Strategy A/B 不可直接相减；配对 A/B bootstrap 为 `NOT_RUN`。",
        "",
    ]
    return "\n".join(lines)


